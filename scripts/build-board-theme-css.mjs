#!/usr/bin/env node
/**
 * Regenerate `src/components/chessboard/styles/board-*.css` with valid
 * two-tone board assets.
 *
 * Background
 * ----------
 * The earlier hand-written data URIs were corrupt, which made the board
 * render as a single flat colour. This script regenerates each theme's
 * CSS deterministically:
 *
 *  - `background-color` = the theme's light-square colour (Chessground
 *    treats the light squares as the board background), and
 *  - `background-image` = an SVG data URI that paints the 32 dark
 *    squares over that background, in the theme's dark-square colour.
 *
 * The colour pairs are Lichess's canonical board-theme palettes:
 *
 *   theme   light      dark
 *   brown   #f0d9b5    #b58863
 *   blue    #dee3e6    #8ca2ad
 *   green   #e9ecd7    #79a36b
 *   purple  #f0d9b5    #aa88bb
 *   wood    #f0d9b5    #b58863
 *
 * (purple/wood use the classic Lichess images; wood is rendered as the
 * classic brown pair.)
 *
 * The other board rules (last-move / check highlighting) are shared and
 * added verbatim by this generator so every theme file stays complete.
 * Legal-move destination/selection markers are intentionally NOT themed:
 * they fall back to Chessground's own default styling.
 *
 * Run with: `node scripts/build-board-theme-css.mjs`
 * Re-run after changing a palette. Output files are checked in.
 */
import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = dirname(here);
const outDir = join(root, 'src/components/chessboard/styles');

const THEMES = {
  brown: { light: '#f0d9b5', dark: '#b58863' },
  blue: { light: '#dee3e6', dark: '#8ca2ad' },
  green: { light: '#e9ecd7', dark: '#79a36b' },
  purple: { light: '#f0d9b5', dark: '#aa88bb' },
  wood: { light: '#f0d9b5', dark: '#b58863' },
};

/** Build an SVG that fills the 32 dark squares of an 8x8 board. */
function darkSquaresSvg(dark) {
  const rects = [];
  for (let row = 0; row < 8; row += 1) {
    for (let col = 0; col < 8; col += 1) {
      if ((row + col) % 2 === 1) {
        rects.push(`<rect x="${col}" y="${row}" width="1" height="1" fill="${dark}"/>`);
      }
    }
  }
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 8 8" shape-rendering="crispEdges">${rects.join('')}</svg>`;
}

const shared = `
.theme-name cg-board square.last-move {
  background-color: rgba(155, 199, 0, 0.41);
}

.theme-name cg-board square.check {
  background: radial-gradient(
    ellipse at center,
    rgba(255, 0, 0, 1) 0%,
    rgba(231, 0, 0, 0.5) 25%,
    rgba(169, 0, 0, 0) 90%
  );
}
`;

async function main() {
  await mkdir(outDir, { recursive: true });
  for (const [name, palette] of Object.entries(THEMES)) {
    const svg = darkSquaresSvg(palette.dark);
    const dataUri = `url('data:image/svg+xml;base64,${Buffer.from(svg, 'utf8').toString('base64')}')`;
    const body = shared.split('.theme-name').join(`.board-${name}`);
    const css = `/*
 * Board theme: ${name}.
 *
 * Generated by \`scripts/build-board-theme-css.mjs\` — do not edit by hand.
 *
 * Light squares: ${palette.light} (board background).
 * Dark squares: ${palette.dark} (SVG overlay).
 * Colour pair matches the Lichess ${name} board-theme palette.
 */
.board-${name} cg-board {
  background-color: ${palette.light};
  background-image: ${dataUri};
}

${body.trim()}
`;
    await writeFile(join(outDir, `board-${name}.css`), css);
  }
  console.log(`[board-theme-css] regenerated ${Object.keys(THEMES).length} theme files`);
}

main().catch((err) => {
  console.error(err);
  process.exitCode = 1;
});
